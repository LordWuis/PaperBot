def p(text: str, style: str = "body"):
    return Paragraph(text, STYLES[style])


def bullets(items):
    return ListFlowable([ListItem(p(item), leftIndent=12) for item in items], bulletType="bullet", leftIndent=14, bulletFontSize=7)


def table(rows, widths=None, header=True):
    data = [[Paragraph(str(cell), STYLES["table"]) for cell in row] for row in rows]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0, hAlign="LEFT")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e6f0f2") if header else colors.white),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#12343b")),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#c9d4da")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafb")]),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return t


