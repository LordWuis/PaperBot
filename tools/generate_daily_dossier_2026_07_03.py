def esc(text: str) -> str:
    return html.escape(text, quote=False)


def link(label: str, url: str) -> str:
    return f'<link href="{html.escape(url, quote=True)}" color="#0969da">{esc(label)}</link>'


def sid(source_id: str) -> str:
    source = next(s for s in SOURCES if s[0] == source_id)
